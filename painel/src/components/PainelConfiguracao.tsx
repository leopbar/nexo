import { estimarCusto, modelosProntos, usd } from './PainelAgentes'

type ChaveNumerica = { [K in keyof ConfigOperacao]: ConfigOperacao[K] extends number ? K : never }[keyof ConfigOperacao]

function Campo({ rotulo, chave, min, max, passo = 1, sufixo }: { rotulo: string; chave: ChaveNumerica; min: number; max: number; passo?: number; sufixo?: string }) {
  const valor = useOperacao((s) => s.config[chave])
  const definir = useOperacao((s) => s.definirConfig)
  return (
    <label className="flex flex-col gap-1">
      <span className="text-[11px] text-zinc-500">{rotulo}</span>
      <div className="relative">
        <Input
          type="number"
          min={min}
          max={max}
          step={passo}
          value={valor}
          onChange={(e) => {
            const n = Number(e.target.value)
            if (Number.isFinite(n)) definir({ [chave]: Math.min(max, Math.max(min, n)) } as Partial<ConfigOperacao>)
          }}
          className={sufixo ? 'pr-8' : undefined}
        />
        {sufixo && <span className="pointer-events-none absolute top-1/2 right-2.5 -translate-y-1/2 text-[11px] text-zinc-600">{sufixo}</span>}
      </div>
    </label>
  )
}

function Grupo({ titulo, sistema, children }: { titulo: string; sistema: string; children: ReactNode }) {
  return (
    <Card>
      <CardHeader>
        <CardTitle>{titulo}</CardTitle>
        <span className="text-[10px] text-zinc-600">{sistema}</span>
      </CardHeader>
      <CardContent className="grid grid-cols-2 gap-x-3 gap-y-2.5">{children}</CardContent>
    </Card>
  )
}

function GrupoAgentes() {
  const config = useOperacao((s) => s.config)
  const agentes = useOperacao((s) => s.agentes)
  const definir = useOperacao((s) => s.definirConfig)
  const abrir = useOperacao((s) => s.definirAgentesAberto)
  const prontos = modelosProntos(agentes).length
  const estimativa = estimarCusto(config, agentes)
  const t = useT()
  const pendencia = !agentes?.chave
    ? t('Para iniciar, cadastre a chave da OpenAI.', 'To start, register the OpenAI key.')
    : prontos === 0
      ? t('Para iniciar, ligue ao menos um modelo.', 'To start, turn on at least one model.')
      : null

  return (
    <Card>
      <CardHeader>
        <CardTitle>{t('Agentes de IA', 'AI agents')}</CardTitle>
        <span className="text-[10px] text-zinc-600">{t('sistema de coleta', 'collection system')}</span>
      </CardHeader>
      <CardContent className="flex flex-col gap-2.5">
        <Switch ligado={config.agentes} aoMudar={(agentes) => definir({ agentes })} rotulo={t('Registros gerados por agentes de IA', 'Records generated by AI agents')} />
        {config.agentes && (
          <>
            <div className="grid grid-cols-2 gap-x-3">
              <Campo rotulo={t('Participantes por chamada', 'Participants per call')} chave="loteAgentes" min={1} max={200} />
              <div className="flex flex-col justify-end text-[11px] text-zinc-500">
                <span>
                  ≈ {num(estimativa.chamadas)} {t('chamadas', 'calls')} · ≈ {usd(estimativa.custo)}
                </span>
                <span>
                  {prontos} {t('modelos ligados', 'models on')}
                </span>
              </div>
            </div>
            {pendencia && <p className="text-[11px] text-amber-300">{pendencia}</p>}
            <p className="text-[11px] text-zinc-600">
              {t(
                'Vazios e inválidos ficam a cargo dos modelos; se uma chamada falhar, aquele lote é gerado por amostragem com os percentuais acima.',
                'Empty and invalid records are up to the models; if a call fails, that batch is generated by sampling with the percentages above.',
              )}
            </p>
          </>
        )}
        <Button variant="secondary" size="sm" onClick={() => abrir(true)}>
          <Bot /> {t('Chave e modelos', 'Key and models')}
        </Button>
      </CardContent>
    </Card>
  )
}

export function PainelConfiguracao() {
  const config = useOperacao((s) => s.config)
  const definir = useOperacao((s) => s.definirConfig)
  const sortear = useOperacao((s) => s.sortearMapa)
  const topologia = useOperacao((s) => s.topologia)
  const participantesMedio = ((config.participantesMin + config.participantesMax) / 2) * config.numUnidades
  const coberturaMedia = (config.coberturaMin + config.coberturaMax) / 200
  const t = useT()

  return (
    <div className="flex flex-col gap-3">
      <div className="px-1">
        <h2 className="text-sm font-medium text-zinc-200">{t('Configuração da operação', 'Operation configuration')}</h2>
        <p className="mt-0.5 text-xs text-zinc-500">
          ≈ {num(participantesMedio)} {t('participantes', 'participants')}, ≈ {num(participantesMedio * coberturaMedia)}{' '}
          {t('registros esperados. Tudo é editável até iniciar.', 'expected records. Everything is editable until start.')}
        </p>
      </div>

      <Grupo titulo={t('Coleta', 'Collection')} sistema={t('sistema de coleta', 'collection system')}>
        <Campo rotulo={t('Número de unidades', 'Number of units')} chave="numUnidades" min={1} max={16} />
        <Campo rotulo={t('Número de itens', 'Number of items')} chave="numItens" min={2} max={8} />
        <Campo rotulo={t('Participantes mín.', 'Min. participants')} chave="participantesMin" min={10} max={50000} passo={100} />
        <Campo rotulo={t('Participantes máx.', 'Max. participants')} chave="participantesMax" min={10} max={50000} passo={100} />
        <Campo rotulo={t('Cobertura mín.', 'Min. coverage')} chave="coberturaMin" min={1} max={100} sufixo="%" />
        <Campo rotulo={t('Cobertura máx.', 'Max. coverage')} chave="coberturaMax" min={1} max={100} sufixo="%" />
        <Campo rotulo={t('Registro vazio', 'Empty record')} chave="probVazio" min={0} max={50} passo={0.5} sufixo="%" />
        <Campo rotulo={t('Registro inválido', 'Invalid record')} chave="probInvalido" min={0} max={50} passo={0.5} sufixo="%" />
        <Campo rotulo={t('Duração', 'Duration')} chave="duracao" min={10} max={3600} passo={10} sufixo="s" />
        <Campo rotulo={t('Registro e atualização', 'Record and update')} chave="intervaloRegistro" min={0.5} max={10} passo={0.5} sufixo="s" />
        <Campo rotulo={t('Checkpoint', 'Checkpoint')} chave="intervaloCheckpoint" min={1} max={120} sufixo="s" />
        <Campo rotulo={t('Participantes por ponto', 'Participants per dot')} chave="participantesPorPonto" min={1} max={200} />
      </Grupo>

      <GrupoAgentes />

      <Grupo titulo={t('Distribuição', 'Distribution')} sistema={t('distribuidor das unidades', 'unit distributor')}>
        <Campo rotulo={t('Tamanho do pacote', 'Package size')} chave="tamanhoPacote" min={10} max={10000} passo={50} sufixo={t('registros', 'records')} />
        <Campo rotulo={t('Janela de envio', 'Send window')} chave="janelaEnvio" min={1} max={16} />
        <Campo rotulo={t('Latência mín.', 'Min. latency')} chave="latenciaMin" min={0.5} max={60} passo={0.5} sufixo="s" />
        <Campo rotulo={t('Latência máx.', 'Max. latency')} chave="latenciaMax" min={0.5} max={60} passo={0.5} sufixo="s" />
        <Campo rotulo={t('Timeout de ACK', 'ACK timeout')} chave="timeoutAck" min={1} max={120} sufixo="s" />
        <Campo rotulo={t('Máx. tentativas', 'Max. attempts')} chave="maxTentativas" min={1} max={20} />
      </Grupo>

      <Grupo titulo={t('Falhas da rede', 'Network failures')} sistema={t('transporte simulado', 'simulated transport')}>
        <Campo rotulo={t('Perda de pacote', 'Package loss')} chave="taxaPerda" min={0} max={60} passo={0.5} sufixo="%" />
        <Campo rotulo={t('Corrupção', 'Corruption')} chave="taxaCorrupcao" min={0} max={60} passo={0.5} sufixo="%" />
        <Campo rotulo={t('Atraso extremo', 'Extreme delay')} chave="taxaAtrasoExtremo" min={0} max={60} passo={0.5} sufixo="%" />
        <Campo rotulo={t('Unidades offline', 'Offline units')} chave="eventosOffline" min={0} max={16} sufixo={t('ev.', 'ev.')} />
      </Grupo>

      <Card>
        <CardHeader>
          <CardTitle>{t('Semente e mapa', 'Seed and map')}</CardTitle>
          <span className="text-[10px] text-zinc-600">{t('todos', 'all')}</span>
        </CardHeader>
        <CardContent className="flex flex-col gap-2">
          <div className="flex gap-2">
            <Input placeholder={t('aleatória', 'random')} value={config.seed} onChange={(e) => definir({ seed: e.target.value })} />
            <Button variant="secondary" size="icon" onClick={sortear} title={t('Sortear outro mapa', 'Generate another map')}>
              <Dices />
            </Button>
          </div>
          <p className="text-[11px] text-zinc-600">
            {t('Com semente, a operação inteira é reprodutível. Sem ela, só o mapa é fixo', 'With a seed, the whole operation is reproducible. Without it, only the map is fixed')} (
            {nomeTerritorio(topologia.nomeTerritorio)}).
          </p>
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle>{t('Itens', 'Items')}</CardTitle>
        </CardHeader>
        <CardContent className="flex flex-col gap-1.5">
          {config.nomesItens.map((nome, i) => (
            <div key={i} className="flex flex-col gap-1">
              <div className="flex items-center gap-2">
                <span className="h-3 w-3 shrink-0 rounded-sm" style={{ background: corItem(i) }} />
                <Input value={nome} onChange={(e) => definir({ nomesItens: config.nomesItens.map((n, j) => (j === i ? e.target.value : n)) })} />
              </div>
              {config.agentes && (
                <Input
                  className="ml-5 w-[calc(100%-1.25rem)] text-xs"
                  maxLength={200}
                  placeholder={t('descrição curta para os agentes (opcional)', 'short description for the agents (optional)')}
                  value={config.descricoesItens[i] ?? ''}
                  onChange={(e) => definir({ descricoesItens: config.descricoesItens.map((d, j) => (j === i ? e.target.value : d)) })}
                />
              )}
            </div>
          ))}
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle>{t('Unidades', 'Units')}</CardTitle>
          <span className="text-[10px] text-zinc-600">{t('latência = comprimento da tubulação', 'latency = pipeline length')}</span>
        </CardHeader>
        <CardContent className="flex flex-col gap-1.5">
          {topologia.unidades.map((f, i) => (
            <div key={f.id} className="flex items-center gap-2">
              <span className="h-2.5 w-2.5 shrink-0 rounded-full" style={{ background: f.cor }} />
              <Input value={config.nomesUnidades[i]} onChange={(e) => definir({ nomesUnidades: config.nomesUnidades.map((n, j) => (j === i ? e.target.value : n)) })} />
              <span className="w-10 shrink-0 text-right font-mono text-[11px] text-zinc-500">{f.latenciaBase.toFixed(1)}s</span>
            </div>
          ))}
        </CardContent>
      </Card>
    </div>
  )
}
